-- Переход на password_hash() для паролей и на HMAC для графических ключей.
--
-- Хеш password_hash() (bcrypt) занимает 60 символов, HMAC-SHA256 графического ключа -- 64,
-- а столбцы user.password и user.graph_key сейчас varchar(50). Расширяем их ДО выкладки нового кода.
--
-- Безопасно выполнять заранее: старый код продолжит работать, существующие значения не меняются.
-- Синтаксис MODIFY одинаково работает и в MariaDB, и в MySQL.
--
-- Сами хеши пересохраняются автоматически: при первом успешном входе пользователя
-- старый хеш (функция password()) заменяется на новый. Сбрасывать пароли не нужно.

ALTER TABLE `user` MODIFY `password` varchar(255) NOT NULL;
ALTER TABLE `user` MODIFY `graph_key` varchar(255) NOT NULL;
